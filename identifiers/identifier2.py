# Validity of Python Identifiers

print("2value   -> Invalid (Identifiers cannot start with a digit)")
print("value_2  -> Valid (Starts with a letter and contains letters, digits, and underscore)")
print("_hidden  -> Valid (Can start with an underscore)")
print("class    -> Invalid ('class' is a Python keyword)")
print("my-var   -> Invalid (Hyphen '-' is not allowed in identifiers)")
print("MyClass  -> Valid (Starts with a letter and uses only letters)")
print("total$   -> Invalid (Special character '$' is not allowed)")

