# LAB 03 - Task 1
# Declare variables and print their values with data types

name = "asif"
age = 18
height = 178.5
is_student = True

print("Name:", name, "Type:", type(name))
print("Age:", age, "Type:", type(age))
print("Height:", height, "Type:", type(height))
print("Student:", is_student, "Type:", type(is_student))

# Output:
# Name: asif Type: <class 'str'>
# Age: 18 Type: <class 'int'>
# Height: 178.5 Type: <class 'float'>
# Student: True Type: <class 'bool'>