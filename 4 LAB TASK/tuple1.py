# Q1. Creating a tuple

countries = ("India", "USA", "Japan", "Australia", "Germany", "France")

print("Tuple:", countries)
print("Type:", type(countries))
print("Length:", len(countries))

# OUTPUT:
# Tuple: ('India', 'USA', 'Japan', 'Australia', 'Germany', 'France')
# Type: <class 'tuple'>
# Length: 6