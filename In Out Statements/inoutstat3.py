# LAB 05 - Task 3
# Three output formatting methods

name = "asif"
marks = 95

# Comma-separated print()
print("Name:", name, "Marks:", marks)

# str.format()
print("Name: {} Marks: {}".format(name, marks))

# f-string
print(f"Name: {name} Marks: {marks}")

# Output:
# Name: asif Marks: 95
# Name: asif Marks: 95
# Name: asif Marks: 95